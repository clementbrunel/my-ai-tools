// Picks the update to offer from the GitHub releases of the monorepo (tags `cbl-log-vX.Y.Z`; the other
// tools of the repository publish their own tags there and are ignored). Pure: no network, no Electron.

export const RELEASES_URL = "https://api.github.com/repos/clementbrunel/my-ai-tools/releases?per_page=50";
const TAG_PREFIX = "cbl-log-v";

/** Subset of the GitHub REST "release" object used here. */
export interface GitHubAsset {
  name: string;
  size: number;
  browser_download_url: string;
  /** "sha256:<hex>" (absent on old releases). */
  digest?: string | null;
}
export interface GitHubRelease {
  tag_name: string;
  html_url: string;
  body?: string | null;
  draft: boolean;
  prerelease: boolean;
  assets: GitHubAsset[];
}

/** Installed build (NSIS installer) or portable `.exe`: they update from different assets. */
export type InstallKind = "setup" | "portable";

/** What the in-app update panel (renderer) shows; the main process drives it. */
export type UpdatePanelState =
  | { kind: "available"; version: string; current: string; notes: string; canInstall: boolean; portable: boolean }
  | { kind: "downloading"; version: string; received: number; total: number }
  | { kind: "uptodate"; current: string }
  | { kind: "error"; title: string; message: string };

/** User's answer to an "available" panel. "notes" opens the release page and keeps the panel open. */
export type UpdateAction = "install" | "notes" | "dismiss";

export interface AvailableUpdate {
  version: string;
  notes: string;
  pageUrl: string;
  asset: GitHubAsset;
}

/** Release channel (settings.updateChannel): "beta" also offers the pre-releases (`3.3.0-beta.1`). */
export type UpdateChannel = "stable" | "beta";

export interface Version {
  core: [number, number, number];
  /** Pre-release identifiers (`beta.1` -> ["beta", 1]); empty for a release. */
  pre: (string | number)[];
}

/** "1.2.3" or "1.2.3-beta.1" (semver, no build metadata); undefined for anything else. */
export function parseVersion(text: string): Version | undefined {
  const m = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?$/.exec(text.trim());
  if (!m) return undefined;
  const pre = m[4] ? m[4].split(".").map((id) => (/^\d+$/.test(id) ? Number(id) : id)) : [];
  return { core: [Number(m[1]), Number(m[2]), Number(m[3])], pre };
}

/** Semver precedence of pre-release identifiers: numbers < words, then by value; a shorter list first. */
function comparePre(a: readonly (string | number)[], b: readonly (string | number)[]): number {
  if (a.length === 0 || b.length === 0) return (a.length === 0 ? 1 : 0) - (b.length === 0 ? 1 : 0); // release > pre-release
  for (let i = 0; i < Math.min(a.length, b.length); i++) {
    const x = a[i]!;
    const y = b[i]!;
    if (x === y) continue;
    if (typeof x === "number" && typeof y === "number") return x - y;
    if (typeof x === "number") return -1;
    if (typeof y === "number") return 1;
    return x < y ? -1 : 1;
  }
  return a.length - b.length;
}

/** Negative if a < b, 0 if equal, positive if a > b (semver: 3.3.0-beta.1 < 3.3.0-beta.2 < 3.3.0). Unparsable versions sort lowest. */
export function compareVersions(a: string, b: string): number {
  const va = parseVersion(a);
  const vb = parseVersion(b);
  if (!va || !vb) return (va ? 1 : 0) - (vb ? 1 : 0);
  return va.core[0] - vb.core[0] || va.core[1] - vb.core[1] || va.core[2] - vb.core[2] || comparePre(va.pre, vb.pre);
}

/** Asset names produced by electron-builder.yml (`artifactName`). */
export const assetName = (kind: InstallKind, version: string): string =>
  kind === "setup" ? `cbl-log-Setup-${version}.exe` : `cbl-log-${version}-portable.exe`;

/**
 * Release body (the version's section of cbl-log/CHANGELOG.md, see the release-tool skill) -> markdown
 * lines the update panel renders like the "Notes de version" window (parseNotes). Bodies generated by
 * GitHub (list of merged PRs, releases up to 2.0.0) give "": the panel then only offers the full history.
 */
export function cleanReleaseBody(body: string | null | undefined): string {
  const text = (body ?? "").trim();
  if (/^## What's Changed/m.test(text)) return "";
  return text
    .split(/\r?\n/)
    .filter((l) => !/^\s*\*\*Full Changelog\*\*/i.test(l) && !/^#+\s/.test(l))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * Newest published cbl-log release strictly newer than `current` that carries the asset for `kind`; undefined when up to date.
 * Its notes are those of that version only. The "stable" channel ignores the pre-releases; a beta tester going back
 * to it is offered the next release (3.3.0 > 3.3.0-beta.2), never an older one.
 */
export function findUpdate(releases: readonly GitHubRelease[], current: string, kind: InstallKind, channel: UpdateChannel = "stable"): AvailableUpdate | undefined {
  let best: AvailableUpdate | undefined;
  for (const r of releases) {
    if (r.draft || !r.tag_name.startsWith(TAG_PREFIX)) continue;
    const version = r.tag_name.slice(TAG_PREFIX.length);
    const parsed = parseVersion(version);
    // a pre-release is recognised by the GitHub flag or by its version suffix
    const pre = r.prerelease || (parsed?.pre.length ?? 0) > 0;
    if (pre && channel !== "beta") continue;
    if (!parsed || compareVersions(version, current) <= 0) continue;
    if (best && compareVersions(version, best.version) <= 0) continue;
    const asset = r.assets.find((a) => a.name === assetName(kind, version));
    if (asset) best = { version, notes: cleanReleaseBody(r.body), pageUrl: r.html_url, asset };
  }
  return best;
}

/** Expected SHA-256 (hex) of an asset, when GitHub provides it. */
export function expectedSha256(asset: GitHubAsset): string | undefined {
  const m = /^sha256:([0-9a-f]{64})$/i.exec(asset.digest ?? "");
  return m ? m[1]!.toLowerCase() : undefined;
}
