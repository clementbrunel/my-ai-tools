describe("formatReleaseNotes", () => {
  it("keeps only the feature titles of generated notes", () => {
    expect(formatReleaseNotes(GENERATED)).toBe(
      ["• Add splash screen and About dialog with branding", "• Redesign command bar and status bar UI", "• Lignes vides soulignées"].join("\n"),
    );
  });

  it("keeps a hand-written body, minus the changelog link", () => {
    expect(formatReleaseNotes("Note: nouvelle vue.\n\n**Full Changelog**: https://x")).toBe("Note: nouvelle vue.");
    expect(formatReleaseNotes(null)).toBe("");
  });
});

describe("findUpdate notes", () => {
  const body = (title: string): string => `* cbl-log: ${title} by @u in https://x/pull/1`;

  it("gathers the notes of every skipped version, newest first", () => {
    const releases = [
      release("cbl-log-v1.2.0", { body: body("feature B") }),
      release("cbl-log-v1.1.0", { body: body("feature A") }),
      release("cbl-log-v1.0.0", { body: body("old feature") }),
    ];
    expect(findUpdate(releases, "1.0.0", "setup")?.notes).toBe("Version 1.2.0\n• Feature B\n\nVersion 1.1.0\n• Feature A");
    expect(findUpdate(releases, "1.1.0", "setup")?.notes).toBe("• Feature B");
  });
});

describe("expectedSha256", () => {
  it("reads GitHub's sha256 digest and ignores anything else", () => {
    const hex = "a".repeat(64);
    expect(expectedSha256({ name: "x", size: 1, browser_download_url: "", digest: `sha256:${hex}` })).toBe(hex);
    expect(expectedSha256({ name: "x", size: 1, browser_download_url: "", digest: null })).toBeUndefined();
    expect(expectedSha256({ name: "x", size: 1, browser_download_url: "" })).toBeUndefined();
  });
});
